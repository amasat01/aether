/**
 * @file PacketExpLogTables.h
 * @brief 128-entry lookup tables for the table-driven `exp` and `log` of
 *        `PacketExpLog.h` (bit patterns, so a gather reads them as integers).
 *
 * The scheme (a 2^(i/128) table for exp, an (1/c, log c) table for log, each
 * with a short polynomial) is the one published in ARM's optimized-routines
 * (https://github.com/ARM-software/optimized-routines, math/exp.c and
 * math/log.c; MIT OR Apache-2.0 WITH LLVM-exception). The VALUES below were
 * regenerated for aether from the definitions with 200-bit arithmetic:
 *
 *   kExpTab[2i]   = bits of t_i,  2^(i/128) = H_i (1 + t_i), H_i = fl(2^(i/128))
 *   kExpTab[2i+1] = bits(H_i) - (i << 45)       (the exponent is added back
 *                                                from the integer k = round(x*128/ln2))
 *   kLogTab[2i]   = bits of 1/c_i, kLogTab[2i+1] = bits of logc_i, a multiple of 2^-42
 *                   (so k*ln2hi + logc_i is exact for |k| < 2^11). 1/c_i was searched
 *                   among 2^22 neighbouring doubles of the cell centre for the one
 *                   whose log(c_i) lies closest to such a multiple (error <= 0.01 ULP
 *                   of log c_i); the cell holding z = 1 has c = 1, log c = 0. The cell index and exponent come
 *                   from the bits of x - 0x3fe6000000000000 (z in [0.6875, 1.375)),
 *                   |z/c - 1| <= 2^-7 on every cell.
 */

