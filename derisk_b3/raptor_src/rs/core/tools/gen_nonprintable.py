"""Writes rs/core/src/nonprintable.rs: the code point ranges Python's repr escapes (str.isprintable() is False), for the Unicode
version of the interpreter that runs this script. Usage: python3 gen_nonprintable.py > ../src/nonprintable.rs"""
import sys, unicodedata
ranges, start = [], None
for cp in range(0x110000):
    np = not chr(cp).isprintable()
    if np and start is None: start = cp
    if not np and start is not None: ranges.append((start, cp - 1)); start = None
if start is not None: ranges.append((start, 0x10FFFF))
print(f"// GENERATED by tools/gen_nonprintable.py from Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}. Do not edit.")
print(f"pub const UNICODE_VERSION: &str = \"{unicodedata.unidata_version}\";")
print("/// Inclusive ranges of the code points that str.isprintable() rejects (repr writes them as an escape).")
print("pub static NONPRINTABLE: &[(u32, u32)] = &[")
for a, b in ranges: print(f"    (0x{a:x}, 0x{b:x}),")
print("];")
