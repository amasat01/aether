"""Mint (or verify) the C reference corpus under tests/c_core/.

The corpus is the plain-C99 reference arithmetic generated by
``aether_dsc.c_core`` for both widths. It is committed as many small headers,
one per width and shape (``corpus/f64/vec3.h``, ``corpus/f32/mat2x3.h``, ...,
plus ``quat.h`` and ``scalar.h``), and one umbrella, ``aether_c_corpus.h``, that
includes them all in a fixed order. aether's tests include the umbrella beside
the C++ templates and compare bit for bit (tests/test_CCore_common.h);
tests/c_core/check_c99.sh compiles the umbrella and every part alone as strict
C99. A part is self-contained: it carries the typedefs and structs it needs
behind include guards, and each function appears in exactly one part.

It is regenerated only when the core changes (``aether_dsc.c_core``, or the
shape corpus below); CI verifies the committed files, it never mints them.

Usage (from anywhere; paths resolve from this script's location):
    python3 tools/c_core/mint_golden.py            # write the corpus (deliberate act)
    python3 tools/c_core/mint_golden.py --check    # regenerate in memory, compare, verify fences
    python3 tools/c_core/mint_golden.py --out DIR  # alternate corpus directory (relative to repo root)

Minting is refused under $CI (exit 2): a gate that regenerates its own
expectation is a tautology. Each part is md5-fenced between its ``CORE BEGIN``
and ``CORE END`` marker lines; the digest covers exactly the bytes between the
BEGIN line's trailing newline and the END line. Minting also removes a part
that the shape corpus no longer produces; ``--check`` reports one as stale.
"""
from __future__ import annotations

import argparse
import difflib
import hashlib
import os
import re
import sys
from pathlib import Path

from aether_dsc import c_core

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_OUT = "tests/c_core"
UMBRELLA = "aether_c_corpus.h"
PARTS_DIR = "corpus"

VECTORS = ((1,), (2,), (3,), (4,), (6,))
MATRICES = ((2, 2), (3, 3), (4, 4), (2, 3), (3, 2))
MM_PAIRS = (((2, 3), (3, 2)), ((3, 3), (3, 3)), ((2, 2), (2, 2)))
OUTER_PAIRS = (((2,), (3,)), ((3,), (3,)))
QUAT_KINDS = ("quat_mul", "quat_conj", "quat_recip", "quat_rotate", "quat_as_pure", "quat_as_vec3")
SCALAR_KINDS = ("rsqrt", "sign", "clip", "remainder")
RAY_KINDS = ("ray_tri", "ray_aabb", "ray_sphere")
MAT_SHAPE_ONLY = ("mat_sum", "mat_mv", "mat_transpose")

BEGIN_FMT = "// ---8<--- CORE BEGIN (md5 = {md5}) ---8<---\n"
END_LINE = "// ---8<--- CORE END ---8<---\n"
BEGIN_RE = re.compile(r"^// ---8<--- CORE BEGIN \(md5 = ([0-9a-f]{32})\) ---8<---\n", re.M)
END_RE = re.compile(r"^// ---8<--- CORE END ---8<---\n", re.M)


def names_for(width: str) -> list[str]:
    """Every corpus entry of one width, in the documented order."""
    names = [c_core.real_typedef(width).name]
    for shape in VECTORS + MATRICES:
        names.append(c_core.struct(shape, width).name)
    vec_kinds = [k for k in c_core.kinds() if k.startswith("vec_") and k != "vec_outer"]
    for shape in VECTORS:
        for kind in vec_kinds:
            if kind == "vec_cross" and shape != (3,):
                continue
            names.append(c_core.function(kind, shape=shape, width=width).name)
    mat_kinds = [k for k in c_core.kinds() if k.startswith("mat_") and k != "mat_mm"]
    for shape in MATRICES:
        for kind in mat_kinds:
            names.append(c_core.function(kind, shape=shape, width=width).name)
    for a, b in MM_PAIRS:
        names.append(c_core.function("mat_mm", shape=a, shape2=b, width=width).name)
    for a, b in OUTER_PAIRS:
        names.append(c_core.function("vec_outer", shape=a, shape2=b, width=width).name)
    for kind in QUAT_KINDS + SCALAR_KINDS + RAY_KINDS:
        names.append(c_core.function(kind, width=width).name)
    return names


def part_key(name: str, width: str) -> str:
    """The part a corpus entry lives in: its shape token (``vec3``, ``mat2x3``,
    ``quat``, ``ray``), or ``scalar`` for the rank-0 functions. The function name is
    ``aether_c_<w>_<shape>_<kind>`` (``mm``/``outer`` name the first shape)."""
    token = name.removeprefix(f"aether_c_{width}_").split("_", 1)[0]
    return token if token.startswith(("vec", "mat", "quat", "ray")) else "scalar"


def parts_for(width: str) -> dict[str, list[str]]:
    """``{part: [corpus entry names]}`` of one width, parts in the order they
    first appear in :func:`names_for`. The typedef and the structs are
    dependencies, pulled into every part that needs them by ``emit``."""
    parts: dict[str, list[str]] = {}
    for name in names_for(width):
        if name == c_core.real_typedef(width).name or name.endswith("_t"):
            continue                       # typedef / struct: emitted as a dependency
        parts.setdefault(part_key(name, width), []).append(name)
    return parts


def part_path(width: str, key: str) -> str:
    return f"{PARTS_DIR}/{width}/{key}.h"


def build_part(width: str, key: str, names: list[str]) -> str:
    block = c_core.emit(names)
    md5 = hashlib.md5(block.encode()).hexdigest()
    head = (
        "// Copyright 2026 Alessandro Masat\n"
        "// SPDX-License-Identifier: Apache-2.0\n"
        "\n"
        "#pragma once\n"
        "\n"
        f"// GENERATED by tools/c_core/mint_golden.py ({c_core.CORE_VERSION}) -- DO NOT EDIT BY HAND\n"
        f"// part: {width} {key} -- included by tests/c_core/{UMBRELLA}\n"
        "// mint: python3 tools/c_core/mint_golden.py\n"
        "\n"
    )
    return head + BEGIN_FMT.format(md5=md5) + block + END_LINE


def build_umbrella(paths: list[str]) -> str:
    lines = [
        "// Copyright 2026 Alessandro Masat\n",
        "// SPDX-License-Identifier: Apache-2.0\n",
        "\n",
        "#pragma once\n",
        "\n",
        f"// GENERATED by tools/c_core/mint_golden.py ({c_core.CORE_VERSION}) -- DO NOT EDIT BY HAND\n",
        "// mint: python3 tools/c_core/mint_golden.py\n",
        "// The whole C reference corpus: one include per part, f64 first, then f32.\n",
        "// consumers: tests/test_CCore_common.h (bit-identity against the templates), "
        "tests/c_core/check_c99.sh (strict C99)\n",
        "\n",
    ]
    lines += [f'#include "{p}"\n' for p in paths]
    return "".join(lines)


def build_files() -> dict[str, str]:
    """``{path relative to the corpus directory: text}`` of every file."""
    files: dict[str, str] = {}
    paths: list[str] = []
    for width in c_core.WIDTHS:
        for key, names in parts_for(width).items():
            path = part_path(width, key)
            files[path] = build_part(width, key, names)
            paths.append(path)
    files[UMBRELLA] = build_umbrella(paths)
    return files


def fence_problem(text: str) -> str | None:
    """None if the fence is intact, else a one-line description."""
    b, e = BEGIN_RE.search(text), END_RE.search(text)
    if not b or not e or e.start() < b.end():
        return "fence markers (CORE BEGIN / CORE END) missing or malformed"
    got = hashlib.md5(text[b.end():e.start()].encode()).hexdigest()
    if got != b.group(1):
        return f"fence md5 mismatch: recorded={b.group(1)} recomputed={got}"
    return None


def summarize_diff(want: str, have: str) -> str:
    wl, hl = want.splitlines(), have.splitlines()
    for i in range(max(len(wl), len(hl))):
        if i >= len(wl) or i >= len(hl) or wl[i] != hl[i]:
            lo = max(0, i - 3)
            diff = difflib.unified_diff(wl[lo:i + 4], hl[lo:i + 4], "expected", "committed",
                                        lineterm="", n=3)
            return f"first difference at line {i + 1}:\n" + "\n".join(diff)
    return "differs only in trailing newline / line endings"


def stale_parts(root: Path, files: dict[str, str]) -> list[str]:
    """Part headers on disk under ``root/corpus`` that the corpus no longer produces."""
    on_disk = {p.relative_to(root).as_posix() for p in (root / PARTS_DIR).rglob("*.h")}
    return sorted(on_disk - set(files))


def check(root: Path, prog: str) -> int:
    files = build_files()
    bad = 0
    for rel, want in files.items():
        path = root / rel
        if not path.is_file():
            print(f"{prog}: RED -- missing {rel}", file=sys.stderr)
            bad += 1
            continue
        have = path.read_bytes().decode()
        problem = fence_problem(have) if rel != UMBRELLA else None
        if problem:
            print(f"{prog}: RED -- {rel}: {problem}", file=sys.stderr)
            bad += 1
        if have != want:
            print(f"{prog}: RED -- {rel} differs from regenerated "
                  f"({len(have.splitlines())} vs {len(want.splitlines())} lines); "
                  f"{summarize_diff(want, have)}", file=sys.stderr)
            bad += 1
    for rel in stale_parts(root, files):
        print(f"{prog}: RED -- stale part {rel} (the corpus no longer produces it)",
              file=sys.stderr)
        bad += 1
    if bad:
        return 1
    print("OK")
    return 0


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="Mint or verify the aether C corpus headers.")
    ap.add_argument("--check", action="store_true", help="verify the committed corpus; no write")
    ap.add_argument("--out", default=DEFAULT_OUT,
                    help=f"corpus root directory (default {DEFAULT_OUT})")
    args = ap.parse_args(argv)
    root = Path(args.out)
    if not root.is_absolute():
        root = REPO_ROOT / root
    prog = "tools/c_core/mint_golden.py"

    if args.check:
        return check(root, prog)

    if os.environ.get("CI"):
        print(f"{prog}: REFUSED -- $CI is set. A gate that regenerates its own expectation "
              "is a tautology; mint locally and commit the diff.", file=sys.stderr)
        return 2
    files = build_files()
    for rel in stale_parts(root, files):
        (root / rel).unlink()
    for rel, text in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode())
    for d in sorted((root / PARTS_DIR).rglob("*"), reverse=True):
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()
    print(f"{prog}: wrote {len(files)} files under {root}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
